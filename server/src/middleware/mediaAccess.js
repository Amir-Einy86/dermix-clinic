const env = require('../config/env');
const M = require('../models');
const { authenticate, requireRole } = require('./auth');
const asyncHandler = require('../utils/asyncHandler');

const published = { published: { $ne: false } };
const consent = { published: true, consent: true };
const sources = [
  [M.GalleryCase, consent, ['beforeImage', 'afterImage']],
  [M.Article, published, ['coverImage']],
  [M.JournalArticle, published, ['coverImage']],
  [M.TeamMember, { active: { $ne: false } }, ['photo']],
];
const canEdit = requireRole('super_admin', 'content_manager');

module.exports = asyncHandler(async (req, res, next) => {
  res.set('Cache-Control', 'no-store');
  // Serve only filenames generated by the uploader.
  if (!/^\/[a-f0-9]{32}\.(jpg|png|webp|mp4|webm)$/.test(req.path)) return res.sendStatus(404);
  const relative = '/uploads' + req.path;
  const urls = env.siteUrl ? [relative, env.siteUrl + relative] : [relative];
  const hits = await Promise.all(sources.map(([model, visible, fields]) => model.exists({
    ...visible, $or: fields.map((field) => ({ [field]: { $in: urls } })),
  })));
  if (hits.some(Boolean)) return next();
  const testimonial = await M.Testimonial.exists({
    ...consent, $or: [{ videoUrl: { $in: urls } }, { thumbnail: { $in: urls } }],
  });
  if (testimonial && (await M.SiteSetting.getSingleton()).showTestimonials) return next();
  if (!req.cookies[env.cookieName] && !req.headers.authorization) return res.sendStatus(404);
  return authenticate(req, res, () => canEdit(req, res, next));
});
